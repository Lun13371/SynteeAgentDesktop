export function buildPlanningInjection(): string {
  return `[РЕЖИМ ПЛАНИРОВАНИЯ АКТИВЕН]
Пользователь хочет получить структурированный план. Твоя задача на этот запрос:
1. Составь детальный план в markdown (# Заголовок, ## Фазы, - [ ] шаги)
2. Вызови инструмент save_plan с готовым планом — он сохранится и отобразится отдельно
3. После вызова save_plan больше ничего не пиши — план уже показан пользователю`
}
