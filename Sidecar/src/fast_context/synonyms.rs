/// English tokens that should also be tried for a Russian token.
pub fn translations(token: &str) -> &'static [&'static str] {
    TABLE.iter().find(|(russian, _)| *russian == token).map(|(_, english)| *english).unwrap_or(&[])
}

/// True when the table knows this token (used by tests and diagnostics).
pub fn is_known(token: &str) -> bool {
    TABLE.iter().any(|(russian, _)| *russian == token)
}

#[cfg(test)]
mod tests {
    use super::{is_known, translations};

    #[test]
    fn core_development_vocabulary_is_covered() {
        assert!(translations("кеш").contains(&"cache"));
        assert!(translations("индексация").contains(&"index"));
        assert!(translations("файл").contains(&"file"));
        assert!(translations("поиск").contains(&"search"));
        assert!(translations("токенов").contains(&"token"));
    }

    #[test]
    fn unknown_tokens_return_an_empty_slice() {
        assert!(translations("совершеннослучайноеслово").is_empty());
        assert!(!is_known("совершеннослучайноеслово"));
    }

    #[test]
    fn table_has_no_duplicate_keys() {
        let mut seen = std::collections::HashSet::new();
        for (russian, _) in super::TABLE {
            assert!(seen.insert(*russian), "duplicate key: {russian}");
        }
    }
}
